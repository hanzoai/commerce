// TestDraftNativeLeavesTheFee checks the arithmetic that decides how much of a
// native balance is actually movable.
//
// Getting it wrong by one wei produces a transaction that is rejected for
// insufficient funds after the fee is applied — the classic way a "sweep
// everything" loop burns gas forever without moving anything.
func TestDraftNativeLeavesTheFee(t *testing.T) {
	n := &node{chainID: 1, nonce: 5, tip: gwei(2), base: gwei(30), gas: 21000, native: eth(1)}
	srv := n.serve(t)
	defer srv.Close()
	c, _ := New(context.Background(), custody.Ethereum, srv.URL)

	d, err := c.Draft(context.Background(), custody.Transfer{
		OrgID: "acme", WalletID: "w1", From: vectorAddr, To: vector1559Dest,
	})
	if err != nil {
		t.Fatal(err)
	}
	_ = d

	// Reconstruct what the code should have reserved: gas*(100+margin)/100 at
	// the cap of base*multiplier + tip.
	gas := uint64(21000) * (100 + gasMargin) / 100
	cap := new(big.Int).Add(new(big.Int).Mul(gwei(30), big.NewInt(feeMultiplier)), gwei(2))
	reserve := new(big.Int).Mul(new(big.Int).SetUint64(gas), cap)
	want := new(big.Int).Sub(eth(1), reserve)

	// The value is not directly observable from the Draft, so assert through
	// the encoding: seal with a real key and decode the result.
	key, _ := crypto.HexToECDSA(vectorKey)
	sig, err := crypto.Sign(d.Digests[0], key)
	if err != nil {
		t.Fatal(err)
	}
	raw, err := d.Seal([][]byte{sig[:64]})
	if err != nil {
		t.Fatal(err)
	}
	var tx types.Transaction
	if err := tx.UnmarshalBinary(raw); err != nil {
		t.Fatal(err)
	}
	if tx.Value().Cmp(want) != 0 {
		t.Fatalf("native sweep value\n got %s\nwant %s (balance minus gas at the fee cap)", tx.Value(), want)
	}
	if tx.Nonce() != 5 {
		t.Fatalf("nonce %d, want the pending count 5", tx.Nonce())
	}
	if tx.GasFeeCap().Cmp(cap) != 0 {
		t.Fatalf("fee cap %s, want %s", tx.GasFeeCap(), cap)
	}
	// And it must be spendable: value + maxfee cannot exceed the balance.
	total := new(big.Int).Add(tx.Value(), new(big.Int).Mul(new(big.Int).SetUint64(tx.Gas()), tx.GasFeeCap()))
	if total.Cmp(eth(1)) > 0 {
		t.Fatalf("drafted a transaction the address cannot afford: needs %s, holds %s", total, eth(1))
	}
}

