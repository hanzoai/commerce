func unhex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(strings.TrimPrefix(s, "0x"))
	if err != nil {
		t.Fatalf("bad hex in test data %q: %v", s, err)
	}
	return b
}

// vector1559Tx rebuilds the external transaction through OUR construction path.
func vector1559Tx(t *testing.T) (*types.Transaction, common.Address) {
	t.Helper()
	to, err := parseAddr(vector1559To)
	if err != nil {
		t.Fatal(err)
	}
	from, err := parseAddr(vectorAddr)
	if err != nil {
		t.Fatal(err)
	}
	dest, err := parseAddr(vector1559Dest)
	if err != nil {
		t.Fatal(err)
	}
	// The calldata is built by transferCall, not pasted, so this asserts our
	// ABI encoding too.
	data := transferCall(dest, big.NewInt(1_000_000_000))
	if got := hex.EncodeToString(data); got != vector1559Data {
		t.Fatalf("transferCall encoded\n got %s\nwant %s", got, vector1559Data)
	}
	return types.NewTx(&types.DynamicFeeTx{
		ChainID:   big.NewInt(1),
		Nonce:     7,
		GasTipCap: big.NewInt(2_000_000_000),
		GasFeeCap: big.NewInt(100_000_000_000),
		Gas:       60000,
		To:        &to,
		Value:     new(big.Int),
		Data:      data,
	}), from
}

// TestSelectorIsKeccak proves the four bytes that choose which function of a
// token contract runs. It hashes the signature rather than trusting the
// constant, because a wrong selector does not fail loudly — on many contracts
// it lands in the fallback and the call succeeds having moved nothing.
func TestSelectorIsKeccak(t *testing.T) {
	want := hex.EncodeToString(crypto.Keccak256([]byte("transfer(address,uint256)"))[:4])
	if want != transferSelector {
		t.Fatalf("transferSelector is %s but keccak256(\"transfer(address,uint256)\")[:4] is %s", transferSelector, want)
	}
}

// TestDigestMatchesExternal proves the bytes we ask the MPC fleet to sign are
// the bytes an independent implementation signs for the same transaction.
//
// This is the single most important assertion in the package. Everything
// downstream — the signature, the assembled transaction, the money — is
// determined by this digest, and a digest that is subtly wrong yields a
// perfectly valid signature over the wrong payload.
func TestDigestMatchesExternal(t *testing.T) {
	tx, from := vector1559Tx(t)
	c := &Chain{network: custody.Ethereum, chainID: big.NewInt(1)}
	d, err := c.draft(tx, from)
	if err != nil {
		t.Fatal(err)
	}
	if len(d.Digests) != 1 {
		t.Fatalf("an account-model chain must produce exactly one digest, got %d", len(d.Digests))
	}
	if got := hex.EncodeToString(d.Digests[0]); got != vector1559Digest {
		t.Fatalf("signing digest\n got %s\nwant %s (eth-account)", got, vector1559Digest)
	}
}

// TestSealMatchesExternal feeds a signature THIS CODE DID NOT PRODUCE into
// Seal and requires the assembled transaction to be byte-identical to the one
// eth-account produced.
//
// The signature comes in as bare r‖s — the shape mpcd returns, minus the
// recovery byte — so this also proves that recovering v ourselves lands on the
// same value the external implementation chose.
func TestSealMatchesExternal(t *testing.T) {
	tx, from := vector1559Tx(t)
	c := &Chain{network: custody.Ethereum, chainID: big.NewInt(1)}
	d, err := c.draft(tx, from)
	if err != nil {
		t.Fatal(err)
	}

	sig := append(unhex(t, vector1559R), unhex(t, vector1559S)...)
	if len(sig) != 64 {
		t.Fatalf("external r‖s should be 64 bytes, got %d", len(sig))
	}

	raw, err := d.Seal([][]byte{sig})
	if err != nil {
		t.Fatalf("Seal refused a signature that is genuinely from the right key: %v", err)
	}
	if got := hex.EncodeToString(raw); got != vector1559Raw {
		t.Fatalf("assembled transaction\n got %s\nwant %s (eth-account)", got, vector1559Raw)
	}

	// And the transaction hash the chain will know it by.
	var decoded types.Transaction
	if err := decoded.UnmarshalBinary(raw); err != nil {
		t.Fatal(err)
	}
	if got := strings.TrimPrefix(decoded.Hash().Hex(), "0x"); got != vector1559Hash {
		t.Fatalf("tx hash\n got %s\nwant %s (eth-account)", got, vector1559Hash)
	}
}

// TestRecoveryIdIsDerivedNotTrusted feeds the signer's v byte in as BOTH
// possible values and requires the same correct answer each time.
//
// mpcd returns a v and checks it against the wallet's own public key. Trusting
// it would make our check circular: it would confirm the signer agrees with
// itself, when the question is whether the signer agrees with the address
// commerce recorded and told a customer to pay into.
func TestRecoveryIdIsDerivedNotTrusted(t *testing.T) {
	tx, from := vector1559Tx(t)
	c := &Chain{network: custody.Ethereum, chainID: big.NewInt(1)}
	d, err := c.draft(tx, from)
	if err != nil {
		t.Fatal(err)
	}
	base := append(unhex(t, vector1559R), unhex(t, vector1559S)...)

	for _, v := range []byte{0, 1} {
		sig := append(append([]byte{}, base...), v)
		raw, err := d.Seal([][]byte{sig})
		if err != nil {
			t.Fatalf("v=%d: Seal refused: %v", v, err)
		}
		if got := hex.EncodeToString(raw); got != vector1559Raw {
			t.Fatalf("v=%d: assembled transaction differs from the external vector\n got %s\nwant %s", v, got, vector1559Raw)
		}
	}
	if vector1559V != 1 {
		t.Fatalf("test data drifted: external v is %d", vector1559V)
	}
}

// TestSealRefusesForeignSignature is the check that stands between a confused
// signer and somebody else's money.
//
// A wrong wallet id, a reshared key, a signer answering on the wrong curve and
// a digest that drifted between drafting and signing all look identical from
// here: a well-formed 64-byte signature that belongs to a different key. None
// of them is detectable by inspecting the signature. All of them must stop.
func TestSealRefusesForeignSignature(t *testing.T) {
	tx, from := vector1559Tx(t)
	c := &Chain{network: custody.Ethereum, chainID: big.NewInt(1)}
	d, err := c.draft(tx, from)
	if err != nil {
		t.Fatal(err)
	}

	// A real signature over the right digest, by the wrong key.
	other, err := crypto.HexToECDSA("1111111111111111111111111111111111111111111111111111111111111111")
	if err != nil {
		t.Fatal(err)
	}
	foreign, err := crypto.Sign(d.Digests[0], other)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := d.Seal([][]byte{foreign}); err == nil {
		t.Fatal("Seal accepted a signature from a key that does not own the custody address")
	} else if !strings.Contains(err.Error(), "does not belong to custody address") {
		t.Fatalf("wrong refusal: %v", err)
	}

	// Garbage of the right length must not be assembled either.
	if _, err := d.Seal([][]byte{make([]byte, 64)}); err == nil {
		t.Fatal("Seal accepted an all-zero signature")
	}
	// And the wrong NUMBER of signatures is refused rather than indexed into.
	if _, err := d.Seal(nil); err == nil {
		t.Fatal("Seal accepted zero signatures")
	}
	if _, err := d.Seal([][]byte{foreign, foreign}); err == nil {
		t.Fatal("Seal accepted two signatures for a one-input transaction")
	}
}

// TestEIP155VectorRecovers checks our address derivation against the signed
// transaction printed in EIP-155 itself — a vector older and more widely
// replicated than any library.
func TestEIP155VectorRecovers(t *testing.T) {
	var tx types.Transaction
	if err := tx.UnmarshalBinary(unhex(t, vectorLegacyRaw)); err != nil {
		t.Fatal(err)
	}
	got, err := types.Sender(types.LatestSignerForChainID(big.NewInt(1)), &tx)
	if err != nil {
		t.Fatal(err)
	}
	if got != common.HexToAddress(vectorAddr) {
		t.Fatalf("EIP-155 vector recovers to %s, want %s", got.Hex(), vectorAddr)
	}
}

// TestParseAddrRefusesTruncation covers the reason parseAddr exists at all.
//
// common.HexToAddress silently zero-pads and truncates, so a destination one
// character short becomes a different, perfectly valid address, and an empty
// string becomes the zero address — a burn.
func TestParseAddrRefusesTruncation(t *testing.T) {
	for _, bad := range []string{
		"",
		"0x",
		"0x9d8A62f656a8d1615C1294fd71e9CFb3E4855A4",   // one nibble short
		"0x9d8A62f656a8d1615C1294fd71e9CFb3E4855A4FF", // one nibble long
		"0x0000000000000000000000000000000000000000",  // burn
		"0xzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzzz",
		"9d8A62f656a8d1615C1294fd71e9CFb3E4855A4",
	} {
		if _, err := parseAddr(bad); err == nil {
			t.Errorf("parseAddr accepted %q", bad)
		}
	}
	// A good address survives, with or without the prefix, in either case.
	for _, good := range []string{vectorAddr, strings.TrimPrefix(vectorAddr, "0x"), strings.ToLower(vectorAddr)} {
		if _, err := parseAddr(good); err != nil {
			t.Errorf("parseAddr rejected %q: %v", good, err)
		}
	}
}

