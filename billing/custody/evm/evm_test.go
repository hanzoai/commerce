// node is a fake EVM JSON-RPC endpoint. It answers only what a sweep asks, and
// records the transaction it was told to broadcast.
type node struct {
	chainID   int64
	nonce     uint64
	tip, base *big.Int
	gas       uint64
	native    *big.Int // wei held by the custody address
	token     *big.Int // token balance of the custody address
	sent      string
	estimated map[string]string // last eth_estimateGas argument
}

func (n *node) serve(t *testing.T) *httptest.Server {
	t.Helper()
	hexb := func(b *big.Int) string { return "0x" + b.Text(16) }
	return httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		var req struct {
			ID     int64  `json:"id"`
			Method string `json:"method"`
			Params []any  `json:"params"`
		}
		if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
			t.Errorf("fake node got undecodable request: %v", err)
			return
		}
		var result any
		switch req.Method {
		case "eth_chainId":
			result = "0x" + big.NewInt(n.chainID).Text(16)
		case "eth_getTransactionCount":
			if len(req.Params) < 2 || req.Params[1] != "pending" {
				t.Errorf("nonce must be read at 'pending', got %v", req.Params)
			}
			result = "0x" + new(big.Int).SetUint64(n.nonce).Text(16)
		case "eth_maxPriorityFeePerGas":
			result = hexb(n.tip)
		case "eth_getBlockByNumber":
			if len(req.Params) < 1 || req.Params[0] != "pending" {
				t.Errorf("base fee must be read from the 'pending' block, got %v", req.Params)
			}
			result = map[string]string{"baseFeePerGas": hexb(n.base)}
		case "eth_estimateGas":
			if m, ok := req.Params[0].(map[string]any); ok {
				n.estimated = map[string]string{}
				for k, v := range m {
					n.estimated[k], _ = v.(string)
				}
			}
			result = "0x" + new(big.Int).SetUint64(n.gas).Text(16)
		case "eth_getBalance":
			result = hexb(n.native)
		case "eth_call":
			result = "0x" + fmt.Sprintf("%064s", n.token.Text(16))
		case "eth_sendRawTransaction":
			n.sent, _ = req.Params[0].(string)
			result = "0x" + vector1559Hash
		default:
			t.Errorf("fake node got an unexpected method %q — a sweep should not need it", req.Method)
		}
		json.NewEncoder(w).Encode(map[string]any{"jsonrpc": "2.0", "id": req.ID, "result": result})
	}))
}

func gwei(n int64) *big.Int { return new(big.Int).Mul(big.NewInt(n), big.NewInt(1_000_000_000)) }
func eth(n int64) *big.Int  { return new(big.Int).Mul(gwei(n), big.NewInt(1_000_000_000)) }

func TestDraftTokenRefusesWithoutGas(t *testing.T) {
	n := &node{
		chainID: 1, nonce: 3, tip: gwei(2), base: gwei(30), gas: 65000,
		native: big.NewInt(0),             // the ordinary state: USDC arrived, no ETH did
		token:  big.NewInt(1_000_000_000), // 1000 USDC
	}
	srv := n.serve(t)
	defer srv.Close()

	c, err := New(context.Background(), custody.Ethereum, srv.URL)
	if err != nil {
		t.Fatal(err)
	}
	_, err = c.Draft(context.Background(), custody.Transfer{
		OrgID: "acme", WalletID: "w1", From: vectorAddr, To: vector1559Dest, Token: vector1559To,
	})
	var noFee *custody.ErrNoFee
	if err == nil {
		t.Fatal("drafted a token transfer from an address with no gas")
	}
	if !asErrNoFee(err, &noFee) {
		t.Fatalf("want a typed ErrNoFee naming what to send, got %T: %v", err, err)
	}
	if noFee.Have.Sign() != 0 || noFee.Need.Sign() <= 0 {
		t.Fatalf("ErrNoFee should say have=0 need>0, got have=%s need=%s", noFee.Have, noFee.Need)
	}
	// Gas must have been estimated with the token contract as the target and
	// the transfer calldata attached — never as a bare value send.
	if got := n.estimated["to"]; got != strings.ToLower(vector1559To) {
		t.Fatalf("estimated gas against %q, want the token contract", got)
	}
	if got := strings.TrimPrefix(n.estimated["data"], "0x"); got != vector1559Data {
		t.Fatalf("estimated gas with data %q, want the transfer calldata", got)
	}
}

