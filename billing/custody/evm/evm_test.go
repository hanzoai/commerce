// TestSweepEndToEnd drives the whole path with a signer that holds the vector
// key: draft against the fake node, sign, seal, broadcast — and requires the
// broadcast bytes to carry a signature the chain will attribute to the custody
// address.
func TestSweepEndToEnd(t *testing.T) {
	n := &node{
		chainID: 1, nonce: 3, tip: gwei(2), base: gwei(30), gas: 65000,
		native: eth(1), token: big.NewInt(1_000_000_000),
	}
	srv := n.serve(t)
	defer srv.Close()

	c, err := New(context.Background(), custody.Ethereum, srv.URL)
	if err != nil {
		t.Fatal(err)
	}
	hash, err := custody.Sweep(context.Background(), c, keySigner{t}, custody.Transfer{
		OrgID: "acme", WalletID: "w1", From: vectorAddr, To: vector1559Dest, Token: vector1559To,
	})
	if err != nil {
		t.Fatal(err)
	}
	if hash == "" {
		t.Fatal("Sweep returned no transaction hash")
	}
	var tx types.Transaction
	if err := tx.UnmarshalBinary(unhex(t, n.sent)); err != nil {
		t.Fatalf("broadcast bytes do not decode as a transaction: %v", err)
	}
	sender, err := types.Sender(types.LatestSignerForChainID(big.NewInt(1)), &tx)
	if err != nil {
		t.Fatal(err)
	}
	if sender != common.HexToAddress(vectorAddr) {
		t.Fatalf("broadcast a transaction from %s, not the custody address %s", sender.Hex(), vectorAddr)
	}
	if tx.To().Hex() != common.HexToAddress(vector1559To).Hex() {
		t.Fatalf("token transfer went to %s, want the token contract %s", tx.To().Hex(), vector1559To)
	}
}

// keySigner stands in for the MPC fleet using the vector's private key. It
// returns bare r‖s, exactly as mpcd's 65-byte answer looks once the recovery
// byte is ignored.
type keySigner struct{ t *testing.T }

func (k keySigner) Sign(_ context.Context, org, wallet string, n custody.Network, digest []byte) ([]byte, error) {
	if org == "" || wallet == "" {
		k.t.Fatalf("signer called without identity: org=%q wallet=%q", org, wallet)
	}
	if c, _ := n.Curve(); c != custody.Secp256k1 {
		k.t.Fatalf("EVM sweep asked for a %s signature", c)
	}
	if len(digest) != 32 {
		k.t.Fatalf("EVM digest should be 32 bytes, got %d", len(digest))
	}
	key, err := crypto.HexToECDSA(vectorKey)
	if err != nil {
		return nil, err
	}
	sig, err := crypto.Sign(digest, key)
	if err != nil {
		return nil, err
	}
	return sig[:64], nil
}

func asErrNoFee(err error, out **custody.ErrNoFee) bool {
	for err != nil {
		if e, ok := err.(*custody.ErrNoFee); ok {
			*out = e
			return true
		}
		u, ok := err.(interface{ Unwrap() error })
		if !ok {
			return false
		}
		err = u.Unwrap()
	}
	return false
}

